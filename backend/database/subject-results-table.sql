-- Create subject_results table to track marks per subject
CREATE TABLE IF NOT EXISTS subject_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id BIGINT REFERENCES results(id) ON DELETE CASCADE,
  subject_id BIGINT REFERENCES subjects(id) ON DELETE CASCADE,
  mark DECIMAL(5,2) NOT NULL CHECK (mark >= 0 AND mark <= 100),
  grade VARCHAR(2),
  remarks TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(result_id, subject_id)
);

-- Create indexes for faster lookups
CREATE INDEX IF NOT EXISTS idx_subject_results_result_id ON subject_results(result_id);
CREATE INDEX IF NOT EXISTS idx_subject_results_subject_id ON subject_results(subject_id);

-- Drop trigger if it exists
DROP TRIGGER IF EXISTS update_subject_results_updated_at ON subject_results;

-- Add a trigger to update the updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ language 'plpgsql';

CREATE TRIGGER update_subject_results_updated_at BEFORE UPDATE ON subject_results
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
